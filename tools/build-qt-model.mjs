// Regenerate the checked-in QJSEngine bundle after changing any of these sources.
import {readFile, writeFile} from 'node:fs/promises';
import {transform} from 'esbuild';
const root = new URL('../', import.meta.url);
const files = ['shared/ui-definitions.js','src/chipdraw/ui-definitions.js','shared/quantity-editor.js','shared/json-store.js','shared/drawing-model.js',
    'shared/rectangle-editor.js','shared/rectangle-help.js','desktop/qt/rectangle-session.js'];
const sources = await Promise.all(files.map(file => readFile(new URL(file, root), 'utf8')));
const {code} = await transform(sources.join('\n'), {target:'es2016', dropLabels:['browserUI'], charset:'utf8', legalComments:'inline'});
const prelude = `// Generated by tools/build-qt-model.mjs for Qt 6.10 QJSEngine.
var globalThis = this;
if (!Object.hasOwn) Object.hasOwn = (value,key) => Object.prototype.hasOwnProperty.call(value,key);
if (!Array.prototype.flatMap) Object.defineProperty(Array.prototype,'flatMap',{
    value:function(fn,owner){return Array.prototype.concat.apply([],this.map(fn,owner));}, configurable:true,writable:true
});
`;
const output = new URL('desktop/qt/chipdraw-model.generated.js', root);
if (process.argv.includes('--check')) {
    if (await readFile(output,'utf8') !== prelude + code) throw Error('Regenerate the Qt model bundle');
} else await writeFile(output, prelude + code);
